# @title
class AlocacaoConjuntosSolver:
    """
    Classe para resolver problema adaptado para a Campanha do Agasalho
    Maximiza a alocação total com pesos
    """

    def __init__(self, nome_problema: str = 'Alocacao_Conjuntos'):
        self.nome_problema = nome_problema
        self.problema = None
        self.variaveis = {}
        self.resultados = None

        # Dados do problema
        self.tipos_roupa = []
        self.entidades = []
        self.estoque_conjuntos = {}
        self.tamanho_conjunto = {}
        self.demandas_pecas = {}
        self.peso_prioridade = {}

    def definir_problema(self,
                         tipos_roupa: List[str],
                         entidades: List[str],
                         estoque_conjuntos: Dict[str, int],
                         tamanho_conjunto: Dict[str, int],
                         demandas_conjuntos: Dict[Tuple[str, str], int],
                         peso_prioridade: Dict[Tuple[str, str], float]) -> None:
        """
        Define os dados do problema com a nova estrutura usando conjuntos
        """
        self.tipos_roupa = tipos_roupa
        self.entidades = entidades
        self.estoque_conjuntos = estoque_conjuntos
        self.tamanho_conjunto = tamanho_conjunto
        self.demandas_conjuntos = demandas_conjuntos
        self.peso_prioridade = peso_prioridade

    def criar_variaveis(self):
        """
        Cria as variáveis de decisão.
        X_{tipo}_{entidade} = número de CONJUNTOS alocados
        """
        for tipo in self.tipos_roupa:
            for entidade in self.entidades:
                nome_variavel = f"X_{tipo}_{entidade}"
                chave = (tipo, entidade)

                max_conjuntos = 0 # Initialize max_conjuntos
                if chave in self.demandas_conjuntos:
                     # Limite superior baseado na demanda em CONJUNTOS
                  max_conjuntos = self.demandas_conjuntos[chave]

                if max_conjuntos > 0:
                    self.variaveis[nome_variavel] = pulp.LpVariable(
                        name=nome_variavel,
                        lowBound=0,
                        upBound=None,
                        cat='Integer'
                    )
                else:
                    self.variaveis[nome_variavel] = pulp.LpVariable(
                        name=nome_variavel,
                        lowBound=0,
                        upBound=0,
                        cat='Integer'
                    )

        print(f"Variáveis criadas: {len(self.variaveis)} variáveis")

    def criar_restricoes(self):
        """
        Cria as restrições do problema
        """
        print("\nCriando restrições...")

        # Restrição 1: Estoque em conjuntos
        print("1. Restrição de estoque por tipo de roupa (em conjuntos):")
        for tipo in self.tipos_roupa:
            soma_conjuntos = pulp.lpSum([
                self.variaveis[f"X_{tipo}_{entidade}"]
                for entidade in self.entidades
                if f"X_{tipo}_{entidade}" in self.variaveis
            ])
            self.problema += soma_conjuntos <= self.estoque_conjuntos.get(tipo, 0), f"Estoque_Conjuntos_{tipo}"
            #print(f"Tipo {tipo}: ∑ conjuntos ≤ {self.estoque_conjuntos.get(tipo, 0)}")

        # Restrição 2: Demanda em CONJUNTOS
        print("\n2. Restrição de demanda em CONJUNTOS:")
        for (tipo, entidade), demanda_conjuntos in self.demandas_conjuntos.items():
            var_nome = f"X_{tipo}_{entidade}"
            if var_nome in self.variaveis and demanda_conjuntos > 0:
                # Agora é direto: alocação <= demanda (ambos em conjuntos)
                self.problema += self.variaveis[var_nome] <= demanda_conjuntos, f"Demanda_Conjuntos_{tipo}_{entidade}"
                #print(f"   {tipo} para {entidade}: {var_nome} ≤ {demanda_conjuntos} conjuntos")

        print("\n3. Restrição de não-negatividade: X_ij ≥ 0 (implícita)")

    def definir_funcao_objetivo(self):
        """
        Define a função objetivo MAXIMIZANDO a alocação total ponderada
        Isso garante que todo o estoque disponível será alocado
        """
        print("\nDefinindo a função objetivo (MAXIMIZAR alocação)...")

        if self.problema is None:
            self.problema = pulp.LpProblem(self.nome_problema, pulp.LpMaximize)  # Nesse caso estamos maximizando

        expressao_objetivo = []

        for (tipo, entidade), demanda_conjuntos in self.demandas_conjuntos.items():
            peso = self.peso_prioridade.get((tipo, entidade), 1.0)
            var_nome = f"X_{tipo}_{entidade}"

            if var_nome in self.variaveis and demanda_conjuntos > 0:
                # Benefício = número de conjuntos alocados * peso
                termo = peso * self.variaveis[var_nome]
                expressao_objetivo.append(termo)

        self.problema += pulp.lpSum(expressao_objetivo), "Funcao_Objetivo_Maximizar"
        print(f"Função objetivo: max ∑ peso × (conjuntos_alocados)")
        print(f"Número de termos: {len(expressao_objetivo)}")

    def resolver(self, tempo_limite: int = 60, gap: float = 0.01) -> Dict:
        """
        Resolve o problema de otimização
        """
        print(f"\n{'='*60}")
        print("RESOLVENDO PROBLEMA DE ALOCAÇÃO DE CONJUNTOS")
        print(f"{'='*60}")

        if self.problema is None:
            self.problema = pulp.LpProblem(self.nome_problema, pulp.LpMaximize)
            self.criar_variaveis()
            self.definir_funcao_objetivo()
            self.criar_restricoes()

        solver = pulp.PULP_CBC_CMD(msg=True, timeLimit=tempo_limite, gapRel=gap)

        inicio = time.time()
        status = self.problema.solve(solver)
        self.tempo_resolucao = time.time() - inicio

        valor_objetivo = pulp.value(self.problema.objective)

        self.resultados = {
            'status': pulp.LpStatus[status],
            'tempo_resolucao': self.tempo_resolucao,
            'valor_objetivo': valor_objetivo if valor_objetivo is not None else 0,
            'alocacoes': {},
            'estatisticas': self.calcular_estatisticas()
        }

        # Coletar valores das variáveis
        for nome_var, variavel in self.variaveis.items():
            valor = pulp.value(variavel)
            if valor is not None and valor > 0:
                partes = nome_var.split('_')
                if len(partes) >= 3:
                    tipo_roupa = partes[1]
                    entidade = '_'.join(partes[2:])
                    self.resultados['alocacoes'][nome_var] = {
                        'conjuntos': valor,
                        'pecas': valor * self.tamanho_conjunto.get(tipo_roupa, 1),
                        'tipo_roupa': tipo_roupa,
                        'entidade': entidade
                    }

        return self.resultados

    def calcular_estatisticas(self) -> Dict:
      """
      Calcula estatísticas sobre a solução
      """
      # Calcular demanda total em peças a partir de demandas_conjuntos
      total_demanda_pecas = 0
      for (tipo, _), demanda_conj in self.demandas_conjuntos.items():
          total_demanda_pecas += demanda_conj * self.tamanho_conjunto.get(tipo, 1)

      total_estoque_pecas = sum(
          self.estoque_conjuntos.get(tipo, 0) * self.tamanho_conjunto.get(tipo, 1)
          for tipo in self.tipos_roupa
      )

      estatisticas = {
          'total_estoque_conjuntos': sum(self.estoque_conjuntos.values()),
          'total_estoque_pecas': total_estoque_pecas,
          'total_demanda_pecas': total_demanda_pecas,
          'total_alocado_conjuntos': 0,
          'total_alocado_pecas': 0,
          'deficit_total_pecas': 0,
          'alocacoes_por_tipo': {},
          'alocacoes_por_entidade': {}
      }

      total_alocado_conjuntos = 0
      total_alocado_pecas = 0


      for (tipo, entidade), demanda_conjuntos_val in self.demandas_conjuntos.items():
            var_nome = f"X_{tipo}_{entidade}"
            if var_nome in self.variaveis:
                valor = pulp.value(self.variaveis[var_nome])
                if valor is not None:
                    pecas_alocadas = valor * self.tamanho_conjunto.get(tipo, 1)
                    total_alocado_conjuntos += valor
                    total_alocado_pecas += pecas_alocadas

                    # Estatísticas por tipo
                    if tipo not in estatisticas['alocacoes_por_tipo']:
                        estatisticas['alocacoes_por_tipo'][tipo] = {'conjuntos': 0, 'pecas': 0}
                    estatisticas['alocacoes_por_tipo'][tipo]['conjuntos'] += valor
                    estatisticas['alocacoes_por_tipo'][tipo]['pecas'] += pecas_alocadas

                    # Estatísticas por entidade
                    if entidade not in estatisticas['alocacoes_por_entidade']:
                        estatisticas['alocacoes_por_entidade'][entidade] = {'conjuntos': 0, 'pecas': 0}
                    estatisticas['alocacoes_por_entidade'][entidade]['conjuntos'] += valor
                    estatisticas['alocacoes_por_entidade'][entidade]['pecas'] += pecas_alocadas


      estatisticas['total_alocado_conjuntos'] = total_alocado_conjuntos

      estatisticas['total_alocado_pecas'] = total_alocado_pecas

      estatisticas['deficit_total_pecas'] = total_demanda_pecas - total_alocado_pecas

      return estatisticas


