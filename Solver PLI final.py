# @title
def calcular_pesos_prioridade(df_resposta: pd.DataFrame,
                               col_entidade: str,
                               col_quantidade: str,
                               col_categorias: str,
                               tipos_roupa_disponiveis: List[str],
                               mapeamento_categorias: Dict) -> Dict:
    """
    Calcula pesos de prioridade baseado na necessidade da entidade

    Args:
        df_resposta: DataFrame com as respostas da entidade
        col_entidade: Nome da coluna com nome da entidade
        col_quantidade: Nome da coluna com nível de necessidade (muito/pouco)
        col_categorias: Nome da coluna com categorias mais necessitadas
        tipos_roupa_disponiveis: Lista de tipos de roupa disponíveis no estoque
        mapeamento_categorias: Mapeamento entre categorias do forms e estoque
        PESO PADRÃO = 1.0

    Returns:
        Dicionário com pesos para cada (tipo_roupa, entidade)
    """
    pesos = {}

    # Mapeamento do nível de necessidade para peso base
    # Quanto maior a necessidade, maior o peso
    peso_por_necessidade = {
        'muito': 2.5,
        'muita': 2.5,
        'alta': 2.5,
        'urgente': 3.0,
        'médio': 2.0,
        'media': 2.0,
        'média': 2.0,
        'pouco': 1.0,
        'baixa': 1.0,
        'normal': 1.5,
        'regular': 1.5
    }

    for idx, row in df_resposta.iterrows():
        entidade = str(row[col_entidade]) if pd.notna(row[col_entidade]) else ''
        if not entidade or entidade.startswith('=IFERROR') or len(entidade) < 5:
            continue

        # 1. Peso base pelo nível de necessidade
        necessidade_texto = str(row[col_quantidade]) if pd.notna(row[col_quantidade]) else 'normal'
        necessidade_texto = necessidade_texto.lower().strip()

        peso_base = 1.0  # peso padrão
        for key, value in peso_por_necessidade.items():
            if key in necessidade_texto:
                peso_base = value
                break

        # 2. Identificar categorias prioritárias da entidade
        categorias_prioritarias = str(row[col_categorias]) if pd.notna(row[col_categorias]) else ''
        categorias_prioritarias = categorias_prioritarias.lower()

        # Lista de categorias que a entidade mais precisa
        categorias_prioritarias_lista = []
        for cat_form, cat_estoque_list in mapeamento_categorias.items():
            if cat_form.lower() in categorias_prioritarias:
                categorias_prioritarias_lista.extend(cat_estoque_list)

        # 3. Calcular peso final para cada tipo de roupa
        for tipo_roupa in tipos_roupa_disponiveis:
            # Peso base pela necessidade geral
            peso_final = peso_base

            # Aumenta peso se for uma categoria prioritária para esta entidade
            if tipo_roupa in categorias_prioritarias_lista:
                # Categoria prioritária ganha peso extra
                peso_final *= 2.5
            elif any(cat in tipo_roupa.lower() for cat in ['acessório', 'brinquedo', 'cobertor']):
                # Itens complementares têm peso reduzido
                peso_final *= 1.5
            else:
                # Demais categorias mantêm peso base
                peso_final *= 1.0

            # Garantir que o peso esteja em um range razoável
            peso_final = max(1, min(5.0, peso_final))

            chave = (tipo_roupa, entidade)
            pesos[chave] = peso_final


    return pesos

