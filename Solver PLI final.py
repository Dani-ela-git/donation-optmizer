        print("\n📊 Carregando demandas e calculando pesos das entidades...")

        xl = pd.ExcelFile(caminho)
        sheets = xl.sheet_names

        demandas_conjuntos = {}
        prioridades = {}

        PECAS_POR_PESSOA_REAL = 2      # Para entidades que informaram pessoas
        PECAS_POR_PESSOA_ESTIMADO = 5  # Para entidades que NÃO informaram
        PESSOAS_PADRAO = 50            # Valor padrão quando não informado o numero de pessoas de cada entidade

