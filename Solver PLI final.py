def carregar_demandas_planilha_entidades(caminho: str,
                                          estoque_conjuntos: Dict[str, int],
                                          tamanho_conjunto: Dict[str, int],
                                          usar_pesos_personalizados: bool = True) -> Tuple[Dict, Dict]:
    """
    Carrega demandas e calcula pesos de prioridade personalizados
    Entidades que informaram pessoas usam 2 peças/pessoa
    Entidades que NÃO informaram usam 5 peças/pessoa (estimativa com 50 pessoas)
    """
